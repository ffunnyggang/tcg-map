-- FUNY PIN coin flip daily statistics
-- KST (Asia/Seoul) calendar day boundary.

create table if not exists public.coin_flip_events (
  id bigint generated by default as identity primary key,
  outcome smallint not null check (outcome in (0,1)),
  flip_date date not null default ((now() at time zone 'Asia/Seoul')::date),
  created_at timestamptz not null default now()
);

alter table public.coin_flip_events enable row level security;

drop policy if exists "coin flips readable for current kst day" on public.coin_flip_events;
create policy "coin flips readable for current kst day"
on public.coin_flip_events
for select
to anon, authenticated
using (flip_date = ((now() at time zone 'Asia/Seoul')::date));

drop policy if exists "coin flips insert current kst day" on public.coin_flip_events;
create policy "coin flips insert current kst day"
on public.coin_flip_events
for insert
to anon, authenticated
with check (flip_date = ((now() at time zone 'Asia/Seoul')::date));

revoke all on public.coin_flip_events from anon, authenticated;
grant select, insert on public.coin_flip_events to anon, authenticated;
grant usage, select on sequence public.coin_flip_events_id_seq to anon, authenticated;

drop view if exists public.v_coin_flip_daily_stats;
create view public.v_coin_flip_daily_stats
with (security_invoker = true)
as
select
  flip_date,
  count(*)::bigint as total_count,
  count(*) filter (where outcome = 0)::bigint as heads_count,
  count(*) filter (where outcome = 1)::bigint as tails_count
from public.coin_flip_events
group by flip_date;

grant select on public.v_coin_flip_daily_stats to anon, authenticated;

create index if not exists coin_flip_events_flip_date_idx
  on public.coin_flip_events (flip_date);
