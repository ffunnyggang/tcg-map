create table if not exists public.market_seller_verifications (
  user_id uuid primary key references auth.users(id) on delete cascade,
  verification_provider text,
  verification_status text not null default 'pending',
  provider_transaction_id text,
  phone_verified boolean not null default false,
  verified_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint market_seller_verifications_status_check
    check (verification_status in ('pending','verified','revoked'))
);

create table if not exists public.market_external_seller_accounts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null,
  external_seller_id text not null,
  external_seller_handle text,
  verification_status text not null default 'verified',
  verification_method text not null default 'listing_challenge',
  verified_listing_external_id text,
  verified_at timestamptz not null default now(),
  last_checked_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint market_external_accounts_provider_check
    check (provider in ('daangn','bunjang','break')),
  constraint market_external_accounts_status_check
    check (verification_status in ('pending','verified','revoked')),
  constraint market_external_accounts_method_check
    check (verification_method in ('listing_challenge','manual_admin')),
  constraint market_external_accounts_provider_seller_unique
    unique (provider, external_seller_id),
  constraint market_external_accounts_user_provider_seller_unique
    unique (user_id, provider, external_seller_id)
);

create index if not exists market_external_accounts_user_idx
  on public.market_external_seller_accounts(user_id, provider, verification_status);

create table if not exists public.market_external_verification_challenges (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null,
  external_listing_id text not null,
  external_seller_id text,
  challenge_code_hash text not null,
  challenge_hint text,
  status text not null default 'pending',
  attempts integer not null default 0,
  expires_at timestamptz not null,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  constraint market_external_challenges_provider_check
    check (provider in ('daangn','bunjang','break')),
  constraint market_external_challenges_status_check
    check (status in ('pending','verified','expired','failed','cancelled'))
);

create index if not exists market_external_challenges_user_idx
  on public.market_external_verification_challenges(user_id, created_at desc);
create index if not exists market_external_challenges_lookup_idx
  on public.market_external_verification_challenges(provider, external_listing_id, status);

create table if not exists public.market_listing_reports (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.market_listings(id) on delete cascade,
  reporter_user_id uuid references auth.users(id) on delete set null,
  report_type text not null,
  reason text,
  status text not null default 'received',
  processed_at timestamptz,
  processed_by uuid references auth.users(id) on delete set null,
  admin_note text,
  created_at timestamptz not null default now(),
  constraint market_listing_reports_type_check
    check (report_type in ('rights','fraud','prohibited','sold_or_unavailable','other')),
  constraint market_listing_reports_status_check
    check (status in ('received','reviewing','hidden','resolved','dismissed'))
);

create index if not exists market_listing_reports_listing_idx
  on public.market_listing_reports(listing_id, created_at desc);
create index if not exists market_listing_reports_status_idx
  on public.market_listing_reports(status, created_at desc);

create table if not exists public.market_listing_audit_logs (
  id bigint generated by default as identity primary key,
  listing_id uuid references public.market_listings(id) on delete set null,
  actor_user_id uuid references auth.users(id) on delete set null,
  event_type text not null,
  event_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists market_listing_audit_listing_idx
  on public.market_listing_audit_logs(listing_id, created_at desc);

alter table public.market_listings
  add column if not exists external_account_id uuid references public.market_external_seller_accounts(id) on delete set null,
  add column if not exists source_last_checked_at timestamptz,
  add column if not exists source_refresh_count integer not null default 0,
  add column if not exists source_status text not null default 'unknown',
  add column if not exists hidden_reason text,
  add column if not exists hidden_at timestamptz;

alter table public.market_listings
  drop constraint if exists market_listings_source_status_check;
alter table public.market_listings
  add constraint market_listings_source_status_check
  check (source_status in ('unknown','active','sold','deleted','unavailable'));

alter table public.market_seller_verifications enable row level security;
alter table public.market_external_seller_accounts enable row level security;
alter table public.market_external_verification_challenges enable row level security;
alter table public.market_listing_reports enable row level security;
alter table public.market_listing_audit_logs enable row level security;

revoke all on public.market_seller_verifications from anon, authenticated;
revoke all on public.market_external_seller_accounts from anon, authenticated;
revoke all on public.market_external_verification_challenges from anon, authenticated;
revoke all on public.market_listing_reports from anon, authenticated;
revoke all on public.market_listing_audit_logs from anon, authenticated;

grant select on public.market_seller_verifications to authenticated;
grant select on public.market_external_seller_accounts to authenticated;
grant select, insert on public.market_listing_reports to authenticated;

drop policy if exists market_seller_verifications_owner_read on public.market_seller_verifications;
create policy market_seller_verifications_owner_read
on public.market_seller_verifications
for select to authenticated
using (user_id = (select auth.uid()));

drop policy if exists market_external_accounts_owner_read on public.market_external_seller_accounts;
create policy market_external_accounts_owner_read
on public.market_external_seller_accounts
for select to authenticated
using (user_id = (select auth.uid()));

drop policy if exists market_listing_reports_reporter_insert on public.market_listing_reports;
create policy market_listing_reports_reporter_insert
on public.market_listing_reports
for insert to authenticated
with check (
  reporter_user_id = (select auth.uid())
  and exists (
    select 1 from public.market_listings l
    where l.id = listing_id
  )
);

drop policy if exists market_listing_reports_reporter_read on public.market_listing_reports;
create policy market_listing_reports_reporter_read
on public.market_listing_reports
for select to authenticated
using (reporter_user_id = (select auth.uid()));
