const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('products.html','utf8');
const filter=fs.readFileSync('products-shop-filter.js','utf8');
const graded=fs.readFileSync('graded-products-v1.js','utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(Boolean);
for(const [i,code] of scripts.entries())new vm.Script(code,{filename:'products.html:inline-'+i});
assert(/products-shop-filter\.js\?v=20261104-/.test(html));
assert(html.includes('window.BOX_PRODUCTS=BOX_PRODUCTS'));
assert(html.includes('const allEntries=quotes.sources.filter'));
assert(html.includes("selectedShop?'판매가 ':'최저 '"));
assert(html.includes('funy:box-shop-quotes-ready'));
assert(filter.includes("kindTabs.after(node)"));
assert(filter.includes("aria-pressed"));
assert(filter.includes("v_app_shops"));
assert(filter.includes("shop_id")||filter.includes("sellerShopIds"));
assert(graded.includes("funy:graded-shops-ready"));
assert(graded.includes("window.FUNY_PRODUCT_SHOP_FILTER?.selected"));
assert(graded.includes("items.filter(p=>!p.is_sample)"));
const config={window:{}};
vm.runInNewContext(fs.readFileSync('products-hobbyselect.js','utf8'),config);
const online=config.window.FUNY_HOBBYSELECT_BOX;
assert.equal(online.name,'하비셀렉트');
assert.equal(online.shopKey,'online:hobbyselect');
assert.equal(online.url,'https://hobbyselect.co.kr/category/BOX/24/');
assert.equal(Object.keys(online.quotes).length,7);
assert.deepEqual(Object.values(online.quotes).sort((a,b)=>a-b),[109000,138000,183000,185000,189000,201000,265000]);
const catalog=new Set(JSON.parse(fs.readFileSync('data/box-products-v1.json','utf8')).products.map(p=>p.id));
for(const id of Object.keys(online.quotes))assert(catalog.has(id),'Unknown BOX id: '+id);
assert(fs.existsSync(online.logo));
assert(html.includes('products-hobbyselect.js?v=20261104-hobby1'));
assert(html.includes('...staticRows'));
assert(filter.includes("document.createElement(external?'a':'button')"));
assert(filter.includes("!id.startsWith('online:')"));
console.log('PASS products shop selector & Hobby Select static checks; inline scripts:',scripts.length);
